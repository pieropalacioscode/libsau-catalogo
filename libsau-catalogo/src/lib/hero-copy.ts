export type HeroIcon = keyof typeof HERO_ICONS;

const MAX_TRUST = 3;
const clean = (s: string | undefined) => (s ?? "").replace(/\s+/g, " ").trim();

export function heroCopy(home: HomeConfig) {
  const trust = home.trust
    .map((t) => {
      const text = clean(t.text);
      const known = Object.prototype.hasOwnProperty.call(HERO_ICONS, t.icon);
      return { text, short: clean(t.short) || text, path: HERO_ICONS[known ? t.icon : "star"] };
    })
    .filter((t) => t.text)
    .slice(0, MAX_TRUST);
  return {
    eyebrow: clean(home.eyebrow),
    headline: [clean(home.headline[0]), clean(home.headline[1])] as [string, string],
    subtitle: clean(home.subtitle),
    trust,
  };
}
